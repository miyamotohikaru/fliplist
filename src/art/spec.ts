// カセット1本ぶんの寸法。ここだけが全ドット絵の共通の約束事。
//
// 実機のカセットを撮ったドット絵（参照画像）は 54x40 前後の小さなスプライトだった。
// カタログの主役として見せるにはもう少し密度が要るので、その約1.6倍を採る。
// これ以上大きくすると「スプライト」ではなく「イラスト」に見えてしまう。

export const CART = {
  /** カセット全体（影は含まない） */
  W: 88,
  H: 64,
  /**
   * ラベル紙の貼られる凹み。ラベル絵はこの中だけを描く。
   * 実機を測ると上の余白より下の余白のほうが広い（16% : 24%）。その比に合わせてある。
   */
  LABEL_X: 10,
  LABEL_Y: 9,
  LABEL_W: 68,
  LABEL_H: 40,
  /** 落ち影のぶんだけ右下に確保する余白 */
  PAD_R: 4,
  PAD_B: 4,
} as const;

/** 影まで含めた描画バッファの大きさ */
export const CART_BUFFER = {
  W: CART.W + CART.PAD_R,
  H: CART.H + CART.PAD_B,
} as const;

/** 画面に出すときの整数倍率 */
export const SCALE = { desktop: 3, tablet: 3, mobile: 2 } as const;
