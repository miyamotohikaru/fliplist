/** 字送り。7x7の字に1pxのあき */
export const MISAKI_ADVANCE = 8;

/** 1行の墨の幅（最後の字のあきを含まない） */
export function misakiWidth(s: string): number {
  return [...s].length * MISAKI_ADVANCE - 1;
}

/**
 * 1行を左上 (x, y) から置く。shadow を渡すと右下1pxに影を先に刷る。
 * 収録していない字は空白として飛ばす。
 */
export function misakiRow(
  g: PixelGfx,
  x: number,
  y: number,
  s: string,
  c: string,
  shadow?: string,
) {
  const passes: Array<[number, string]> = shadow
    ? [
        [1, shadow],
        [0, c],
      ]
    : [[0, c]];
  for (const [off, col] of passes) {
    [...s].forEach((ch, i) => {
      const rows = GLYPHS[ch];
      if (rows) g.blit(x + i * MISAKI_ADVANCE + off, y + off, rows, { "#": col });
    });
  }
}
